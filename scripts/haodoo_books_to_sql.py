#!/usr/bin/env python
"""Generate SQL that adds the books in haodoo_books.json missing from the DB.

haodoo_books.json (2018-03, used by get_haodoo_books.py) is newer than the
2017-10 OpenShift dump. It lists download links only ({link, title,
volumetype}), so the volume id, book id and page URL are derived from the
link, and author is left empty.

    OPENSHIFT_MYSQL_DB_URL=mysql://haodoo:haodoo@127.0.0.1:3306/ \
        uv run python scripts/haodoo_books_to_sql.py data/haodoo_books.json \
        > docker/initdb/02-haodoo-books-2018.sql

The output refers to volumes by their site id rather than by `_id`, so it can
be applied to any DB that holds the 2017 dump. Rows already present are
skipped when generating; re-running the generated SQL is not idempotent.
"""
import json
import os
import re
import sys
from urllib.parse import parse_qs, urlparse

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from haodooscraper.model import Page, Volume, VolumeExt, session  # noqa: E402

# P=<prefix>[V]<rest>.<ext>; mobi links insert "V" after the category prefix,
# e.g. D438.epub / DV438.mobi -> volume D438.
LINK_RE = re.compile(r'^([A-Z]+?)(V?)(\d[^.]*)\.(\w+)$')
SITE = 'http://www.haodoo.net/'


def q(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "''") + "'"


def parse_link(book):
    p = parse_qs(urlparse(book['link']).query)['P'][0]
    m = LINK_RE.match(p)
    if not m or (m.group(2) == 'V') != (book['volumetype'] == 'mobi'):
        raise ValueError('unexpected link: {}'.format(book['link']))
    prefix, rest = m.group(1), m.group(3)
    return prefix, prefix + rest, rest


def page_url(prefix, bookid):
    # Category I and the HQ* share pages live under M=Share; A-H under M=book.
    kind = 'Share' if prefix == 'I' or prefix.startswith('HQ') else 'book'
    return '{}?M={}&P={}'.format(SITE, kind, bookid)


def main(path):
    books = json.load(open(path, encoding='utf-8'))
    page_ids = {pid for (pid,) in session.query(Page.id)}
    volume_ids = {vid for (vid,) in session.query(Volume.id)}
    links = {link for (link,) in session.query(VolumeExt.link)}

    new_pages = {}    # bookid -> url
    new_volumes = {}  # volume id -> dict
    new_exts = []     # (volume id, type, link)
    for book in books:
        if book['link'] in links:
            continue
        prefix, vid, rest = parse_link(book)
        if vid not in volume_ids and vid not in new_volumes:
            # Multi-volume sets append a lowercase letter: D17XZa -> page 17XZ.
            bookid = rest if rest in page_ids else re.sub(r'[a-z]+$', '', rest)
            url = page_url(prefix, bookid)
            if bookid not in page_ids:
                new_pages.setdefault(bookid, url)
            new_volumes[vid] = dict(title=book['title'], bookid=bookid,
                                    pageurl=url)
        new_exts.append((vid, book['volumetype'], book['link']))
        links.add(book['link'])

    out = sys.stdout
    out.write('-- Generated by scripts/haodoo_books_to_sql.py from {}\n'
              .format(os.path.basename(path)))
    out.write('-- {} pages, {} volumes, {} download links\n\n'
              .format(len(new_pages), len(new_volumes), len(new_exts)))
    out.write('SET NAMES utf8mb4;\nUSE `haodooscraper`;\n\n')
    for bookid, url in new_pages.items():
        out.write('INSERT INTO bookpages (id, url, title) VALUES ({}, {}, {});\n'
                  .format(q(bookid), q(url), q('')))
    out.write('\n')
    for vid, v in new_volumes.items():
        out.write('INSERT INTO bookvolumes (id, author, title, bookid, pageurl) '
                  'VALUES ({}, {}, {}, {}, {});\n'.format(
                      q(vid), q(''), q(v['title']), q(v['bookid']),
                      q(v['pageurl'])))
    out.write('\n')
    for vid, vtype, link in new_exts:
        out.write('INSERT INTO volumeexts (volumeid, volumetype, link) '
                  'SELECT _id, {}, {} FROM bookvolumes WHERE id = {};\n'
                  .format(q(vtype), q(link), q(vid)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit('usage: {} haodoo_books.json'.format(sys.argv[0]))
    main(sys.argv[1])
